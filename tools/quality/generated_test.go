package main

import (
	"os"
	"path/filepath"
	"testing"
)

func TestGeneratedMarkerDoesNotHideOrdinarySource(t *testing.T) {
	for _, generated := range []bool{true, false} {
		source := "package fixture\n"
		if generated {
			source = "// Code generated by protoc-gen-go. DO NOT EDIT.\n" + source
		}
		path := filepath.Join(t.TempDir(), "record.pb.go")
		if err := os.WriteFile(path, []byte(source), 0600); err != nil {
			t.Fatal(err)
		}
		if got := generatedGo(path); got != generated {
			t.Fatalf("generated=%t, got %t", generated, got)
		}
	}
}
