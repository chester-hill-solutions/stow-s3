package main

import (
	"reflect"
	"testing"
)

func TestLifecycleFlags(t *testing.T) {
	names := map[string]bool{"closed": true, "closing": true, "started": true, "destroyed": true, "isclosed": true}
	tests := []struct {
		name, source string
		flags        []string
	}{
		{"server regression", `type Server struct { started bool; closed bool }`, []string{"closed", "started"}},
		{"workspace regression", `type Workspace struct { closing, closed, destroyed bool }`, []string{"closed", "closing", "destroyed"}},
		{"atomic flags", `type Server struct { started atomic.Bool; closed bool }`, []string{"closed", "started"}},
		{"prefixed names", `type Server struct { isClosed, _closing bool }`, []string{"_closing", "isClosed"}},
		{"anonymous struct", `var state = struct { started, closed bool }{}`, []string{"closed", "started"}},
		{"local inferred flags", `func run() { started := false; closed := true }`, []string{"closed", "started"}},
		{"local typed flags", `func run() { var started, closed bool }`, []string{"closed", "started"}},
		{"local inferred var", `func run() { var started = false; var closed = false }`, []string{"closed", "started"}},
		{"single flag", `type Store struct { closed bool }`, nil},
		{"capabilities", `type Store struct { persistent, multipart bool; closed bool }`, nil},
		{"explicit machine", `type Server struct { lifecycle serverLifecycle }`, nil},
		{"separate owners", `type A struct { started bool }; type B struct { closed bool }`, nil},
		{"nested scopes", `func run() { started := false; if started { closed := false; _ = closed } }`, nil},
		{"separate closures", `func run() { started := false; _ = func() { closed := true; _ = closed }; _ = started }`, nil},
		{"constants", `func run() { const started = false; const closed = true }`, nil},
		{"strings", "var text = `type Server struct { started, closed bool }`", nil},
	}
	for _, item := range tests {
		t.Run(item.name, func(t *testing.T) {
			findings, err := scanSource("fixture.go", []byte("package fixture\n"+item.source), names)
			if err != nil {
				t.Fatal(err)
			}
			var flags []string
			for _, finding := range findings {
				flags = append(flags, finding.Flags...)
			}
			if !reflect.DeepEqual(flags, item.flags) {
				t.Fatalf("findings = %+v, want flags %v", findings, item.flags)
			}
		})
	}
}

func TestMalformedSourceFails(t *testing.T) {
	if _, err := scanSource("bad.go", []byte("package bad; type Broken struct {"), nil); err == nil {
		t.Fatal("malformed source was silently skipped")
	}
}

func TestGeneratedSourceIsExcluded(t *testing.T) {
	text := "// Code generated by fixture. DO NOT EDIT.\npackage fixture\ntype Server struct { started, closed bool }"
	findings, err := scanSource("generated.go", []byte(text), map[string]bool{"started": true, "closed": true})
	if err != nil || len(findings) != 0 {
		t.Fatalf("generated findings = %+v, %v", findings, err)
	}
}

func TestOwnersRemainNamedAcrossLineChanges(t *testing.T) {
	text := "package fixture\nfunc (s *Server[T]) run() { started := false; closed := false }"
	names := map[string]bool{"started": true, "closed": true}
	first, err := scanSource("fixture.go", []byte(text), names)
	if err != nil {
		t.Fatal(err)
	}
	second, err := scanSource("fixture.go", []byte("\n\n"+text), names)
	if err != nil {
		t.Fatal(err)
	}
	if len(first) != 1 || len(second) != 1 || first[0].Owner != "Server.run" || first[0].Owner != second[0].Owner {
		t.Fatalf("unstable owners: %+v / %+v", first, second)
	}
}
